#!/bin/sh

# 1. ตรวจสอบว่าผู้ใช้ไม่ได้ส่งอาร์กิวเมนต์มาเลยหรือไม่ ($# คือจำนวนอาร์กิวเมนต์)
if [ $# -eq 0 ]; then
    echo "No arguments supplied"
else
    # 2. ถ้ามีอาร์กิวเมนต์ ให้ใช้ Loop วนลูปอ่านค่าอาร์กิวเมนต์ทีละตัว
    for arg in "$@"
    do
        # สร้างโฟลเดอร์โดยเติม ex ข้างหน้าชื่ออาร์กิวเมนต์นั้นๆ
        mkdir "ex$arg"
    done
fi
